import { SpectralType } from './universeData';
import { skyPosition } from '@/lib/skyPosition';

export interface ConstellationStar {
  id: string;
  nameEn: string;
  nameAr: string;
  position: [number, number, number];
  magnitude: number;
  spectralType: SpectralType;
  color: string;
}

export interface ConstellationDefinition {
  id: string;
  nameEn: string;
  nameAr: string;
  latinName: string;
  abbreviation: string;
  familyEn: string;
  familyAr: string;
  descriptionEn: string;
  descriptionAr: string;
  loreEn: string;
  loreAr: string;
  centerPosition: [number, number, number];
  boundingRadius: number;
  stars: ConstellationStar[];
  lines: Array<[string, string]>; // Pairs of star IDs to draw asterism lines between
  deepSkyObjects?: string[]; // IDs of celestial bodies belonging inside this constellation
  imageUrl?: string;
  imageSource?: string;
}

// Every star is placed where it really is: J2000 RA/Dec and parallax distance from SIMBAD, through the same
// skyPosition mapping (real direction, log-scaled distance) as the Stars & Relics bodies, so each figure looks right
// seen from the Sun and its stars meet the catalogue bodies (Sirius, Betelgeuse) exactly. Stick figures are the IAU /
// Sky & Telescope figures from Stellarium's "modern_iau" sky culture, or its "modern" one where that is fuller.
// Parallaxes under 1 mas are capped at 1 mas (~3,260 ly): too uncertain for these bright distant giants.
const s = (
  id: string,
  nameEn: string,
  nameAr: string,
  raDeg: number,
  decDeg: number,
  lightYears: number,
  magnitude: number,
  spectralType: SpectralType,
  color: string
): ConstellationStar => ({ id, nameEn, nameAr, position: skyPosition(raDeg, decDeg, lightYears), magnitude, spectralType, color });

// Label at the mean of the stars, sized by the farthest star from it
function define(c: Omit<ConstellationDefinition, 'centerPosition' | 'boundingRadius'>): ConstellationDefinition {
  const n = c.stars.length;
  const center: [number, number, number] = [0, 1, 2].map((k) => c.stars.reduce((sum, st) => sum + st.position[k], 0) / n) as [number, number, number];
  const boundingRadius = Math.max(...c.stars.map((st) => Math.hypot(st.position[0] - center[0], st.position[1] - center[1], st.position[2] - center[2])));
  return { ...c, centerPosition: center.map((v) => Math.round(v)) as [number, number, number], boundingRadius: Math.round(boundingRadius) };
}

